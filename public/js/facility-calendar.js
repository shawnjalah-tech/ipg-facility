(() => {
  'use strict';
  const dialog = document.getElementById('fb-day-dialog');
  const panel = document.getElementById('fb-dialog-body');
  const close = document.getElementById('fb-dialog-close');
  const search = document.getElementById('fb-search');
  const groups = document.getElementById('fb-groups');
  const noResults = document.getElementById('fb-no-search');
  if (search && groups) {
    const categories = [...groups.querySelectorAll('details.fb-category')];
    const originalOpen = new Map(categories.map(category => [category, category.open]));
    search.addEventListener('input', () => {
      const term = search.value.trim().toLocaleLowerCase();
      let visible = 0;
      for (const category of categories) {
        let groupVisible = 0;
        for (const row of category.querySelectorAll('.fb-facility-row')) {
          const match = !term || (row.querySelector('.fb-room-name')?.textContent || '').toLocaleLowerCase().includes(term);
          row.hidden = !match;
          if (match) { groupVisible++; visible++; }
        }
        category.hidden = groupVisible === 0;
        category.open = term ? groupVisible > 0 : originalOpen.get(category);
      }
      if (noResults) noResults.hidden = visible > 0;
    });
  }
  if (!dialog || !panel || typeof dialog.showModal !== 'function') return;
  let request = null;
  close?.addEventListener('click', () => dialog.close());
  dialog.addEventListener('click', (event) => {
    if (event.target === dialog) dialog.close();
  });
  document.addEventListener('click', async (event) => {
    const link = event.target.closest('a[data-day-detail]');
    if (!link || event.button !== 0 || event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return;
    event.preventDefault();
    if (request) request.abort();
    request = new AbortController();
    const url = new URL(link.href, window.location.href);
    if (url.origin !== window.location.origin) { window.location.assign(link.href); return; }
    url.searchParams.set('fragment', '1');
    panel.textContent = 'Loading availability…';
    if (!dialog.open) dialog.showModal();
    try {
      const response = await fetch(url.href, {
        headers: { 'X-Requested-With': 'XMLHttpRequest', 'Accept': 'text/html' },
        credentials: 'same-origin', signal: request.signal,
      });
      if (!response.ok) throw new Error('Could not load day details');
      // The fragment is rendered and escaped by Laravel Blade, never based on arbitrary client data.
      panel.innerHTML = await response.text();
      // Only select IDs generated by our booking links (never arbitrary CSS selectors).
      const bookingId = link.dataset.bookingId;
      if (bookingId && /^\d+$/.test(bookingId)) {
        const item = panel.querySelector('#fb-booking-' + bookingId);
        if (item) {
          item.classList.add('fb-detail-highlight');
          item.scrollIntoView({ block: 'nearest', behavior: 'auto' });
        }
      }
    } catch (error) {
      if (error.name === 'AbortError') return;
      panel.replaceChildren();
      const fallback = document.createElement('a');
      fallback.href = link.href;
      fallback.textContent = 'Open day details in a full page';
      panel.append(document.createTextNode('Day details could not be loaded. '), fallback);
    }
  });
})();
